// Markdown form of the legal documents, written to docs/legal/ by `npm run legal:export`
// (scripts/exportLegal.ts). tests/legal/legalExport.test.ts fails when the files there
// no longer match the text in this folder.

import { legalVersionLine, privacyContactLine } from './meta.ts';
import type { LegalBlock, LegalDocument } from './types.ts';

/** File name in docs/legal/ for each document. */
export const LEGAL_MARKDOWN_FILES = {
  'privacy-notice': 'PRIVACY_NOTICE.md',
  terms: 'TERMS.md',
} as const satisfies Record<LegalDocument['id'], string>;

const GENERATED_NOTE =
  '<!-- Generated from shared/legal by `npm run legal:export`. Do not edit this file; edit shared/legal and export again. -->';

function blockToMarkdown(block: LegalBlock): string {
  if (block.kind === 'paragraph') return block.text;
  return block.items.map((item) => `- ${item}`).join('\n');
}

export function legalDocumentToMarkdown(doc: LegalDocument): string {
  const parts: string[] = [
    GENERATED_NOTE,
    `# ${doc.title}`,
    `_${legalVersionLine()}_`,
    `Contact: ${privacyContactLine()}`,
    ...doc.summary,
  ];
  for (const section of doc.sections) {
    parts.push(`## ${section.heading}`);
    for (const block of section.blocks) parts.push(blockToMarkdown(block));
  }
  return `${parts.join('\n\n')}\n`;
}
